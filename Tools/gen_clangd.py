import os
import sys

# Cờ biên dịch chuẩn cho lõi Cortex-M4 (STM32F446RE)
BASE_FLAGS = [
    "-xc",
    "-mthumb",
    "-mcpu=cortex-m4",
    "-mfpu=fpv4-sp-d16",
    "-mfloat-abi=hard",
    "--target=arm-none-eabi",
    "-Wno-unknown-attributes",
    "-Wno-unknown-warning-option",
    "-Wno-int-conversion",
    "-DUSE_HAL_DRIVER",
    "-DSTM32F446xx",
    # Mượn thư viện C chuẩn trực tiếp từ môi trường UCRT64 trên Windows:
    "-isystemD:/Tools/Msys2/ucrt64/include"
]

def scan_and_generate(project_path):
    include_paths = set()
    print(f"[*] Dang quet project: {project_path}")

    for root, dirs, files in os.walk(project_path):
        if any(ignored in root for ignored in [".git", ".vscode", "Debug", "Release", ".metadata"]):
            continue
            
        for file in files:
            if file.endswith(".h"):
                rel_path = os.path.relpath(root, project_path).replace("\\", "/")
                if rel_path == ".":
                    include_paths.add("-I.")
                else:
                    include_paths.add(f"-I{rel_path}")
                break

    output_file = os.path.join(project_path, "compile_flags.txt")
    with open(output_file, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by gen_clangd.py\n")
        f.write("\n".join(BASE_FLAGS) + "\n\n")
        f.write("# Include Directories\n")
        f.write("\n".join(sorted(include_paths)) + "\n")

    print(f"[+] Da tao xong: {output_file}\n")

def main():
    # Lấy đường dẫn tuyệt đối của thư mục chứa chính script này (tức thư mục Tools)
    script_dir = os.path.dirname(os.path.abspath(__file__))

    # Lùi về thư mục gốc (Modular_Radar_Architecture) rồi đi vào STM32
    base_dir = os.path.abspath(os.path.join(script_dir, "..", "STM32"))
    
    projects = []
    
    if not os.path.exists(base_dir):
        print(f"[-] Khong tim thay thu muc: {base_dir}")
        return

    for item in os.listdir(base_dir):
        full_path = os.path.join(base_dir, item)
        if os.path.isdir(full_path):
            if (os.path.exists(os.path.join(full_path, "Core")) or 
                any(f.endswith(".ioc") for f in os.listdir(full_path)) or
                os.path.exists(os.path.join(full_path, "Services"))):
                projects.append(full_path)

    print("=== DANH SACH PROJECT STM32 ===")
    for idx, p in enumerate(projects):
        print(f"[{idx + 1}] {p}")
    print("[0] Quet va tao cho TAT CA cac project tren")

    choice = input("\nChon project muon gen (mac dinh la 0): ").strip()
    if choice == "" or choice == "0":
        for p in projects:
            scan_and_generate(p)
    else:
        try:
            selected_idx = int(choice) - 1
            if 0 <= selected_idx < len(projects):
                scan_and_generate(projects[selected_idx])
            else:
                print("[-] Lua chon khong hop le!")
        except ValueError:
            print("[-] Vui long nhap so hop le!")

if __name__ == "__main__":
    main()